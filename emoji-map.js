function guessEmoji(name, category) {
  const n = (name || '').trim();
  for (const [keywords, emoji] of KEYWORD_MAP) {
    if (keywords.some((k) => n.includes(k))) return emoji;
  }
  return CATEGORY_FALLBACK[category] || '🍽️';
}

